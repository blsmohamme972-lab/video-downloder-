class Fixture:
    def __init__(self, data, mode='normal', bytes_per_second=0, slow_offset=None, slow_bytes_per_second=0,
                 max_active=None):
        self.data = data
        # Refuse media ranges with 429 while this many bodies are in flight.
        self.max_active = max_active
        self.refused = 0
        self.mode = mode
        self.bytes_per_second = bytes_per_second
        # One media range (not the 1-byte probe) can be served slowly to model
        # a congested or retrying connection.
        self.slow_offset = slow_offset
        self.slow_bytes_per_second = slow_bytes_per_second
        self.requests_when_slow_done = None
        self.requests = []
        self.active = 0
        self.peak = 0
        self.truncated = False
        self.lock = threading.Lock()
        fixture = self

        class Handler(http.server.BaseHTTPRequestHandler):
            protocol_version = 'HTTP/1.1'

            def log_message(self, *args):
                pass

            def do_GET(self):
                if self.headers.get('X-StreamSave-QA') != 'preserved':
                    self.send_error(403)
                    return
                header = self.headers.get('Range')
                match = re.fullmatch(r'bytes=(\d+)-(\d*)', header or '')
                first = int(match[1]) if match else 0
                last = min(int(match[2]) if match and match[2] else len(fixture.data) - 1,
                           len(fixture.data) - 1)
                status = 206 if match else 200
                if fixture.mode in ('ignore_range', 'short_200', 'short_200_no_length'):
                    first, last, status = 0, len(fixture.data) - 1, 200
                    if fixture.mode.startswith('short_200'):
                        last = min(last, 194)
                if first >= len(fixture.data):
                    self.send_error(416)
                    return
                with fixture.lock:
                    fixture.requests.append((first, last, header))
                    counted = last - first + 1 > 65536
                    refused = (counted and fixture.max_active is not None
                               and fixture.active >= fixture.max_active)
                    if refused:
                        fixture.refused += 1
                        counted = False
                    if counted:
                        fixture.active += 1
                        fixture.peak = max(fixture.peak, fixture.active)
                    truncate = (fixture.mode == 'truncate_once' and last - first > 65536
                                and not fixture.truncated)
                    if truncate:
                        fixture.truncated = True
                if refused:
                    self.send_error(429)
                    return
                try:
                    self.send_response(status)
                    if status == 206:
                        reported_first = first + (1 if fixture.mode == 'bad_range' else 0)
                        total = len(fixture.data) + (1 if fixture.mode == 'bad_total' else 0)
                        self.send_header('Content-Range', f'bytes {reported_first}-{last}/{total}')
                    if fixture.mode != 'short_200_no_length':
                        self.send_header('Content-Length', str(last - first + 1))
                    else:
                        self.send_header('Connection', 'close')
                        self.close_connection = True
                    self.send_header('ETag', '"stable-fixture"')
                    self.send_header('Content-Type', 'application/octet-stream')
                    self.end_headers()
                    send_last = first + (last - first) // 2 if truncate else last
                    slow = first == fixture.slow_offset and last - first + 1 > 65536
                    rate = fixture.slow_bytes_per_second if slow else fixture.bytes_per_second
                    start = time.monotonic()
                    sent = 0
                    for offset in range(first, send_last + 1, 64 * 1024):
                        block = fixture.data[offset:min(send_last + 1, offset + 64 * 1024)]
                        if rate:
                            delay = (sent + len(block)) / rate - (time.monotonic() - start)
                            if delay > 0:
                                time.sleep(delay)
                        if slow and offset + len(block) >= send_last + 1:
                            # Recorded before the final bytes leave, so the
                            # client cannot yet have appended this piece.
                            with fixture.lock:
                                fixture.requests_when_slow_done = len(fixture.requests)
                        if offset + len(block) >= send_last + 1 and counted:
                            # A completed response is no longer an in-flight
                            # body, even while its handler finishes cleanup.
                            with fixture.lock:
                                fixture.active -= 1
                                counted = False
                        self.wfile.write(block)
                        self.wfile.flush()
                        sent += len(block)
                    if truncate:
                        self.close_connection = True
                except (BrokenPipeError, ConnectionResetError):
                    pass
                finally:
                    if counted:
                        with fixture.lock:
                            fixture.active -= 1

        self.server = http.server.ThreadingHTTPServer(('127.0.0.1', 0), Handler)
        self.server.daemon_threads = True
        self.thread = threading.Thread(target=self.server.serve_forever, daemon=True)
        self.thread.start()
        self.url = f'http://127.0.0.1:{self.server.server_port}/generated.bin'

    def close(self):
        self.server.shutdown()
        self.server.server_close()
        self.thread.join()


def transfer(url, length, destination, *, stock=False, progress=None, retries=1):
    options = {
        'quiet': True, 'noprogress': True, 'continuedl': True,
        'retries': retries, 'socket_timeout': 3, 'http_chunk_size': 10 * 1024 * 1024,
        'buffersize': 64 * 1024, 'overwrites': False,
    }
    info = {
        'id': 'offline-fixture', 'extractor_key': 'Youtube', 'extractor': 'youtube',
        'format_id': '137', 'url': url, 'filesize': length, 'ext': 'mp4',
        'protocol': 'http', 'http_headers': {'X-StreamSave-QA': 'preserved'},
    }
    with YoutubeDL(options) as ydl:
        cls = HttpFD if stock else get_suitable_downloader(info, options)
        downloader = cls(ydl, options)
        if progress is not None:
            downloader.add_progress_hook(lambda s: progress.append(dict(s)))
        return downloader.download(str(destination), info)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def ready(process):
    marker = process.stdout.readline().strip()
    if not marker.startswith('STREAMSAVE_WORKER:'):
        raise AssertionError(f'Unexpected supervisor greeting: {marker}')
    worker_pid = int(marker.split(':')[1])
    process.stdin.write('READY\n')
    process.stdin.flush()
    return worker_pid


class ParallelTransferTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        # Nonperiodic bytes catch reordered/duplicated ranges, not just length errors.
        cls.data = random.Random(20261106).randbytes(64 * 1024 * 1024 + 371)

    def setUp(self):
        self.directory = tempfile.TemporaryDirectory(prefix='streamsave-qa-')
        self.destination = Path(self.directory.name) / 'media.f137.mp4'
        self.fixtures = []

    def tearDown(self):
        for fixture in self.fixtures:
            fixture.close()
        self.directory.cleanup()

    def fixture(self, size=20 * 1024 * 1024 + 179, **kwargs):
        result = Fixture(self.data[:size], **kwargs)
        self.fixtures.append(result)
        return result

    def assert_complete(self, fixture):
        self.assertEqual(digest(fixture.data), digest(self.destination.read_bytes()))
        self.assertFalse(Path(str(self.destination) + '.part').exists())

    def test_native_fragment_downloader_is_not_wrapped(self):
        self.assertIs(original_http_method, HttpFD.real_download)
        self.assertIs(original_http_method, HttpQuietDownloader.real_download)
        for protocol in ('http_dash_segments', 'm3u8_native'):
            cls = get_suitable_downloader({'url': 'https://example.invalid/a', 'protocol': protocol}, {})
            self.assertNotEqual('StreamSaveHttpFD', cls.__name__)

    def test_parallel_bytes_and_legacy_prefix_resume(self):
        fixture = self.fixture()
        prefix = 1_047_552  # Deliberately not aligned to either 8 MiB or 10 MiB.
        part = Path(str(self.destination) + '.part')
        part.write_bytes(fixture.data[:prefix])
        progress = []
        transfer(fixture.url, len(fixture.data), self.destination, progress=progress)
        self.assert_complete(fixture)
        self.assertIn(prefix, [first for first, last, _ in fixture.requests if last - first > 65536])
        self.assertTrue(all(last - first + 1 <= adapter.PIECE_SIZE for first, last, _ in fixture.requests))
        self.assertTrue(all(s.get('downloaded_bytes', 0) <= len(fixture.data) for s in progress))

    def test_ignored_range_falls_back_only_for_fresh_file(self):
        fixture = self.fixture(size=2 * 1024 * 1024 + 19, mode='ignore_range')
        transfer(fixture.url, len(fixture.data), self.destination)
        self.assert_complete(fixture)
        self.destination.unlink()
        prefix = fixture.data[:123_457]
        part = Path(str(self.destination) + '.part')
        part.write_bytes(prefix)
        with self.assertRaises(DownloadError):
            transfer(fixture.url, len(fixture.data), self.destination)
        self.assertEqual(prefix, part.read_bytes())
        self.assertFalse(self.destination.exists())

    def test_bad_content_range_or_total_never_appends(self):
        for mode in ('bad_range', 'bad_total'):
            fixture = self.fixture(size=2 * 1024 * 1024 + 19, mode=mode)
            prefix = fixture.data[:121_231]
            part = Path(str(self.destination) + '.part')
            part.write_bytes(prefix)
            with self.assertRaises(DownloadError):
                transfer(fixture.url, len(fixture.data), self.destination)
            self.assertEqual(prefix, part.read_bytes())
            self.assertFalse(self.destination.exists())

    def test_short_200_error_body_is_never_published(self):
        for mode in ('short_200', 'short_200_no_length'):
            fixture = self.fixture(size=2 * 1024 * 1024 + 19, mode=mode)
            with self.assertRaises(DownloadError):
                transfer(fixture.url, len(fixture.data), self.destination)
            self.assertFalse(self.destination.exists())
            self.assertFalse(Path(str(self.destination) + '.part').exists())

    def test_changed_source_prefix_is_kept_and_rejected(self):
        fixture = self.fixture(size=2 * 1024 * 1024 + 19)
        prefix = fixture.data[:121_230] + b'changed'
        part = Path(str(self.destination) + '.part')
        part.write_bytes(prefix)
        with self.assertRaises(DownloadError):
            transfer(fixture.url, len(fixture.data), self.destination)
        self.assertEqual(prefix, part.read_bytes())

    def test_truncated_range_retries_without_duplicate_bytes(self):
        fixture = self.fixture(mode='truncate_once')
        progress = []
        transfer(fixture.url, len(fixture.data), self.destination, progress=progress)
        self.assert_complete(fixture)
        self.assertTrue(fixture.truncated)
        requests = Counter((first, last) for first, last, _ in fixture.requests)
        self.assertGreater(max(requests.values()), 1)
        amounts = [s.get('downloaded_bytes', 0) for s in progress]
        self.assertTrue(all(a <= len(fixture.data) for a in amounts))

    def test_unknown_size_uses_native_resume(self):
        fixture = self.fixture(size=2 * 1024 * 1024 + 19)
        prefix = 132_789
        Path(str(self.destination) + '.part').write_bytes(fixture.data[:prefix])
        transfer(fixture.url, None, self.destination)
        self.assert_complete(fixture)
        self.assertEqual(prefix, fixture.requests[0][0])

    def test_packaged_launcher_import_and_descendant_shutdown(self):
        command = [sys.executable, '-u', str(RUNNER), str(ENGINE)]
        process = subprocess.Popen(command + ['--version'], stdin=subprocess.PIPE,
                                   stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        ready(process)
        text, _ = process.communicate(timeout=20)
        self.assertEqual(0, process.returncode, text)
        self.assertEqual('2026.10.26', text.strip())
        process = subprocess.Popen(command + ['--streamsave-supervision-test'], stdin=subprocess.PIPE,
                                   stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        worker = ready(process)
        marker = process.stdout.readline().strip()
        self.assertTrue(marker.startswith('STREAMSAVE_TEST_CHILD:'), marker)
        descendant = int(marker.partition(':')[2])
        process.terminate()
        process.communicate(timeout=10)
        self.assertEqual(130, process.returncode)
        self.assertFalse(Path(f'/proc/{worker}').exists())
        self.assertFalse(Path(f'/proc/{descendant}').exists())

    def test_cancel_during_commit_resumes_exact_contiguous_bytes(self):
        fixture = self.fixture()
        process = subprocess.Popen(
            [sys.executable, '-u', __file__, '--fixture-worker', fixture.url,
             str(len(fixture.data)), str(self.destination)],
            stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        worker = ready(process)
        marker = process.stdout.readline().strip()
        self.assertEqual('STREAMSAVE_TEST_COMMIT', marker)
        process.terminate()
        process.communicate(timeout=10)
        self.assertEqual(130, process.returncode)
        self.assertFalse(Path(f'/proc/{worker}').exists())
        part = Path(str(self.destination) + '.part')
        prefix = part.read_bytes()
        self.assertGreater(len(prefix), 0)
        self.assertLess(len(prefix), len(fixture.data))
        self.assertEqual(fixture.data[:len(prefix)], prefix)
        transfer(fixture.url, len(fixture.data), self.destination)
        self.assert_complete(fixture)

    def test_slow_range_does_not_idle_other_connections(self):
        # Small pieces give many ranges; the first media range is 16x slower
        # than the others. Before look-ahead, no new range started until that
        # piece was appended, so the other seven connections sat idle.
        piece = 1024 * 1024
        rate = 4 * 1024 * 1024
        fixture = self.fixture(size=len(self.data), bytes_per_second=rate,
                               slow_offset=0, slow_bytes_per_second=rate // 16)
        original_piece = adapter.PIECE_SIZE
        adapter.PIECE_SIZE = piece
        try:
            transfer(fixture.url, len(fixture.data), self.destination)
        finally:
            adapter.PIECE_SIZE = original_piece
        self.assert_complete(fixture)
        self.assertIsNotNone(fixture.requests_when_slow_done)
        # One probe plus the whole look-ahead window started while the slow
        # range was still in flight. The old schedule allowed only 1 + 8.
        self.assertEqual(fixture.requests_when_slow_done, 1 + adapter.LOOKAHEAD)
        self.assertLessEqual(fixture.peak, adapter.CONNECTIONS)
        self.assertTrue(all(last - first + 1 <= piece for first, last, _ in fixture.requests))

    def test_final_ranges_are_spread_across_connections(self):
        fixture = self.fixture(size=len(self.data))
        transfer(fixture.url, len(fixture.data), self.destination)
        self.assert_complete(fixture)
        sizes = [last - first + 1 for first, last, _ in sorted(fixture.requests) if last - first + 1 > 1]
        # Every range but the very last is between the minimum and maximum
        # piece size, and ranges shrink toward the end of the stream.
        self.assertTrue(all(adapter.MIN_PIECE_SIZE <= size <= adapter.PIECE_SIZE for size in sizes[:-1]))
        self.assertGreater(sizes[0], sizes[-2])
        self.assertGreaterEqual(len(sizes), adapter.CONNECTIONS)

    def test_server_refusals_reduce_connections(self):
        # The server accepts only five bodies at once and answers 429 to the
        # rest. The transfer must retry, back off and still finish intact.
        # (Exact back-off timing is covered by the clock-driven test below.)
        fixture = self.fixture(size=len(self.data), bytes_per_second=8 * 1024 * 1024, max_active=5)
        transfer(fixture.url, len(fixture.data), self.destination, retries=5)
        self.assert_complete(fixture)
        self.assertGreater(fixture.refused, 0)
        self.assertLessEqual(fixture.peak, 5)

    def test_connection_limit_backs_off_and_recovers_on_schedule(self):
        clock = [1000.0]
        with mock.patch.object(adapter.time, 'monotonic', lambda: clock[0]):
            limit = adapter.ConnectionLimit(16, 4)
            limit.back_off()
            self.assertEqual(8, limit.limit)
            limit.back_off()  # Refusals arriving together count once.
            self.assertEqual(8, limit.limit)
            clock[0] += 2.0
            limit.back_off()
            self.assertEqual(4, limit.limit)
            clock[0] += 2.0
            limit.back_off()
            self.assertEqual(4, limit.limit)  # Never below the minimum.
            clock[0] += 29.0
            limit.recover()
            self.assertEqual(4, limit.limit)  # Not before 30 s without refusals.
            clock[0] += 1.0
            limit.recover()
            self.assertEqual(5, limit.limit)
            limit.recover()
            self.assertEqual(5, limit.limit)  # At most one step per 10 s.
            clock[0] += 10.0
            limit.recover()
            self.assertEqual(6, limit.limit)
        stop = threading.Event()
        for _ in range(limit.limit):
            limit.acquire(stop)
        stop.set()
        with self.assertRaises(InterruptedError):
            limit.acquire(stop)  # Full: waits, and gives up once stopped.
        limit.release()
        self.assertEqual(limit.limit - 1, limit.active)

    def test_progress_line_shows_open_connections(self):
        info = {'id': 'offline-fixture', 'extractor_key': 'Youtube', 'url': 'http://127.0.0.1/x',
                'filesize': 10, 'ext': 'mp4', 'protocol': 'https'}
        lines = []
        with YoutubeDL({'quiet': True}) as ydl:
            downloader = get_suitable_downloader(info, {})(ydl, {})
            downloader._multiline = types.SimpleNamespace(
                print_at_line=lambda text, _: lines.append(text), stream=None, allow_colors=False)
            downloader.to_console_title = lambda *args, **kwargs: None
            status = {'status': 'downloading', 'downloaded_bytes': 5, 'total_bytes': 10,
                      'speed': 1024 * 1024, 'eta': 5, 'info_dict': info}
            downloader.report_progress(dict(status, streamsave_connections=12))
            downloader._streamsave_single = True
            downloader.report_progress(dict(status))
        self.assertTrue(lines[0].endswith('ETA 00:05 (12 connections)'), lines[0])
        self.assertTrue(lines[1].endswith('ETA 00:05 (1 connection)'), lines[1])
        # The app reads the percentage from this same line.
        self.assertRegex(lines[0], r'\[download]\s+50\.0%')

    def test_controlled_per_connection_benchmark_and_hashes(self):
        rate = 5 * 1024 * 1024
        stock = self.fixture(size=len(self.data), bytes_per_second=rate)
        begin = time.monotonic()
        transfer(stock.url, len(stock.data), self.destination, stock=True)
        stock_seconds = time.monotonic() - begin
        self.assert_complete(stock)
        self.destination.unlink()
        parallel = self.fixture(size=len(self.data), bytes_per_second=rate)
        begin = time.monotonic()
        transfer(parallel.url, len(parallel.data), self.destination)
        parallel_seconds = time.monotonic() - begin
        self.assert_complete(parallel)
        summary = {
            'generated_bytes': len(self.data), 'sha256': digest(self.data),
            'per_connection_limit_bytes_per_second': rate,
            'stock_seconds': round(stock_seconds, 3), 'parallel_seconds': round(parallel_seconds, 3),
            'ratio': round(stock_seconds / parallel_seconds, 2),
            'stock_peak_requests': stock.peak, 'parallel_peak_requests': parallel.peak,
            'max_parallel_request_bytes': max(b - a + 1 for a, b, _ in parallel.requests),
        }
        print('\nCONTROLLED_BENCHMARK ' + json.dumps(summary, sort_keys=True), flush=True)
        self.assertGreaterEqual(parallel.peak, 4)
        self.assertLessEqual(parallel.peak, adapter.CONNECTIONS)
        # Timing is reported, not asserted: heavily shared CI runners vary.


if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] == '--fixture-worker':
        url, length, path = sys.argv[2:]

        def worker():
            import builtins
            old_open = builtins.open

            class SlowCommit:
                def __init__(self, stream):
                    self.stream = stream
                    self.first = True

                def __enter__(self):
                    return self

                def __exit__(self, *args):
                    return self.stream.__exit__(*args)

                def __getattr__(self, key):
                    return getattr(self.stream, key)

                def write(self, block):
                    # Deliberately exercise short-write handling while making
                    # the verified-piece commit interruptible at a known point.
                    count = self.stream.write(block[:min(4096, len(block))])
                    if self.first:
                        print('STREAMSAVE_TEST_COMMIT', flush=True)
                        self.first = False
                    time.sleep(0.1)
                    return count

            def slow_open(file, mode='r', *args, **kwargs):
                result = old_open(file, mode, *args, **kwargs)
                return SlowCommit(result) if str(file) == path + '.part' and mode == 'ab' else result

            builtins.open = slow_open
            transfer(url, int(length), Path(path))

        sys.exit(adapter.run_supervised(worker))
    unittest.main()
